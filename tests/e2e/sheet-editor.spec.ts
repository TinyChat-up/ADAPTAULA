import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { createReviewedAdaptation, makePdf, signUpAndOnboard, uniqueEmail, uploadAndOpen, waitForAnalysis, workspaceOf } from "./helpers";
import { requireVisuals, seedReadyDocument } from "./adaptation-seed";
import { editorDocument } from "../support/editor-document";

test("editar, deshacer, guardar, recuperar y descargar la misma ficha sin cambiar el original", async ({ page }, info) => {
  test.setTimeout(180000);
  const email = uniqueEmail();
  await signUpAndOnboard(page, email);
  await page.goto("/app/alumnos/nuevo");
  await page.getByLabel("Alias o iniciales").fill("M.R.");
  await page.getByLabel("Etapa").selectOption({ label: "Educación Primaria" });
  await page.getByLabel("Curso").selectOption({ label: "5.º de Primaria" });
  await page.getByRole("button", { name: "Crear perfil" }).click();
  await expect(page).toHaveURL(/\/app\/alumnos/);
  const materialId = await uploadAndOpen(page, { name: "Medidas.pdf", mimeType: "application/pdf", buffer: await makePdf({ marker: email }) });
  await waitForAnalysis(page);
  const id = await createReviewedAdaptation(page, `/app/materiales/${materialId}`);
  await seedReadyDocument(page, await workspaceOf(page, email), id, editorDocument());
  await requireVisuals(page, id, []);
  await page.goto(`/app/adaptaciones/${id}/vista`);
  await page.getByRole("link", { name: "Editar ficha", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Editar ficha", exact: true })).toBeVisible();
  const prompt = page.getByLabel("Enunciado", { exact: true });
  const original = "Compara 25 cm y 40 cm. Explica tu elección.";
  const edited = "Observa las medidas de 25 cm y 40 cm. Justifica tu elección.";
  await prompt.fill(edited);
  await expect(page.getByRole("button", { name: "Guardar borrador" })).toBeDisabled();
  await expect(page.getByText("Has cambiado contenido de la actividad.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Deshacer", exact: true }).click();
  await expect(prompt).toHaveValue(original);
  await page.getByRole("button", { name: "Rehacer", exact: true }).click();
  await expect(prompt).toHaveValue(edited);
  await page.getByLabel("Tamaño de letra", { exact: true }).selectOption("1.3");
  await page.getByLabel("Líneas para responder", { exact: true }).selectOption("8");
  const preview = page.getByRole("region", { name: "Hoja A4, desplazable" });
  await expect(preview.getByText(edited, { exact: true })).toBeVisible();
  await expect(preview.locator(".ms-lines > div")).toHaveCount(8);
  await expect(preview.getByText("25 cm", { exact: true }).first()).toBeVisible();
  await expect(preview.locator("svg").first()).toBeVisible();
  expect(await preview.locator(".ms-num").first().evaluate((el) => {
    const range = document.createRange(); range.selectNodeContents(el); return range.getClientRects().length;
  })).toBe(1);
  await page.getByRole("checkbox", { name: /Entiendo que debo comprobar/ }).check();
  await page.getByRole("button", { name: "Guardar borrador", exact: true }).click();
  await expect(page.getByText("Borrador guardado. La ficha generada sigue intacta.", { exact: true })).toBeVisible();
  await page.reload();
  await expect(prompt).toHaveValue(edited);
  await expect(page.getByLabel("Tamaño de letra", { exact: true })).toHaveValue("1.3");
  await expect(preview.locator(".ms-lines > div")).toHaveCount(8);
  await prompt.fill("Un cambio sin guardar.");
  await expect(page.getByRole("button", { name: "Descargar PDF", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "Recuperar último guardado", exact: true }).click();
  await expect(prompt).toHaveValue(edited);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const a11y = await new AxeBuilder({ page }).exclude(".ms-root").analyze();
  expect(a11y.violations.filter((v) => v.impact === "critical" || v.impact === "serious")).toEqual([]);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: info.outputPath("editor.png"), fullPage: true });
  const downloaded = page.waitForEvent("download", { timeout: 60000 });
  await page.getByRole("button", { name: "Descargar PDF", exact: true }).click();
  const download = await downloaded;
  expect(await download.failure()).toBeNull();
  await download.saveAs(info.outputPath("borrador.pdf"));
  await page.goto(`/app/adaptaciones/${id}/vista?modo=alumno`);
  await expect(page.getByText(original, { exact: true })).toBeVisible();
  await expect(page.getByText(edited, { exact: true })).toHaveCount(0);
  await expect(page.getByText(/CLAVE_RESERVADA_DOCENTE|NOTA_RESERVADA_DOCENTE/)).toHaveCount(0);
});
