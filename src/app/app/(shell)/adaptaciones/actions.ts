/**
 * Public application commands for the adaptation pipeline. Every action: resolves the actor on the SERVER (workspace and role never
 * come from the client), validates its input, calls the application service (the only place with domain rules) and answers with a
 * safe, generic result. None of them calls an AI provider and all of them are fast: a command that needs a stage persists its
 * durable job, and the screen runs that job at once in its own awaited request (`POST /api/adaptations/[id]/run`). Server Actions
 * are dispatched one at a time per client, so a stage that takes minutes must not live here (it would hold back "Cancelar").
 * The daily cron only recovers jobs nobody finished.
 */

async function context() {
  const ctx = await requireWorkspace();
  const supabase = await getSupabase();
  const actor: Actor = { userId: ctx.user.id, workspaceId: ctx.workspace.id, canWrite: hasRole(ctx.role, WRITE_ROLES) };
  return { actor, deps: serviceDeps(supabase) };
}

const Id = z.uuid();

const CreateInput = z.object({
  materialId: Id,
  learnerProfileId: Id.nullable(),
  adaptationType: AdaptationTypeSchema,
  teacherRequest: z.string().trim().max(500).nullable().optional(),
  title: z.string().trim().min(1).max(200).optional(),
  /** Generated by the form once per submit; a double submit reuses the adaptation (and its single reservation). */
  requestKey: z.string().min(8).max(120).optional(),
});

const invalid = <T>(): PublicResult<T> => ({ ok: false, code: "invalid", message: "Revisa los datos y vuelve a intentarlo." });

export async function createAdaptationAction(input: unknown): Promise<PublicResult<{ adaptationId: string }>> {
  const parsed = CreateInput.safeParse(input);
  if (!parsed.success) return invalid();
  const { actor, deps } = await context();
  return toPublic(await createAdaptationCommand(deps, actor, { ...parsed.data, requestKey: parsed.data.requestKey ?? randomUUID() }));
}

/** Entry from an analyzed material: the type is fixed to the accessibility adaptation (the one the pipeline supports today). */
export async function createAdaptationFromMaterialAction(materialId: string, input: { learnerProfileId: string | null; requestKey: string }): Promise<PublicResult<{ adaptationId: string }>> {
  return createAdaptationAction({ materialId, learnerProfileId: input.learnerProfileId, adaptationType: "accessibility", requestKey: input.requestKey });
}

export async function startPlanningAction(adaptationId: string): Promise<PublicResult<EnqueuedDto>> {
  if (!Id.safeParse(adaptationId).success) return toPublic({ ok: false, code: "not_found" });
  const { actor, deps } = await context();
  return toPublic(await startPlanning(deps, actor, adaptationId));
}

const ReviewInput = z.object({
  schema_version: z.literal(1),
  plan_fingerprint: z.string().regex(/^[a-f0-9]{64}$/),
  entries: z.array(z.record(z.string(), z.unknown())).max(60),
});

/** Only decisions and edits are accepted from the client: the reviewer's identity and the time are set by the server. */
export async function submitPlanReviewAction(adaptationId: string, review: unknown): Promise<PublicResult<SubmitReviewDto>> {
  if (!Id.safeParse(adaptationId).success) return toPublic({ ok: false, code: "not_found" });
  const parsed = ReviewInput.safeParse(review);
  if (!parsed.success) return invalid();
  const { actor, deps } = await context();
  return toPublic(await submitPlanReviewCommand(deps, actor, adaptationId, { schema_version: 1, plan_fingerprint: parsed.data.plan_fingerprint, entries: parsed.data.entries }));
}

